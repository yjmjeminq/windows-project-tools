def decode_card_groups(data):
    if len(data) < 4:
        raise ValueError("The card group table has no header")
    group_count, card_count = struct.unpack_from("<HH", data)
    first_id = 4 + 4 * group_count
    if not 0 < group_count <= MAX_GROUPS or card_count > MAX_MEMBERSHIPS:
        raise ValueError("Unsupported 80460 card group table size")
    if len(data) != first_id + 2 * card_count:
        raise ValueError("Invalid 80460 card group table length")

    card_ids = struct.unpack_from(f"<{card_count}H", data, first_id)
    rows = []
    next_offset = 0
    for group, (offset, count) in enumerate(struct.iter_unpack("<HH", data[4:first_id])):
        if offset != next_offset or offset + count > card_count:
            raise ValueError(f"Invalid card group offset at index {group}")
        members = card_ids[offset:offset + count]
        if members != tuple(sorted(set(members))) or (members and not 0 < members[0] <= members[-1] <= 0x7FFF):
            raise ValueError(f"Invalid card IDs at group index {group}")
        rows.append(members)
        next_offset += count
    if next_offset != card_count:
        raise ValueError("Some card IDs are outside the group ranges")
    return rows


def apply_memberships(original):
    rows = decode_card_groups(original)
    missing_groups = max(0, max(MEMBERSHIP_ADDITIONS) + 1 - len(rows))
    rows.extend([()] * missing_groups)
    offsets = bytearray()
    card_ids = []
    added = 0
    for group, members in enumerate(rows):
        updated = tuple(sorted(set(members).union(MEMBERSHIP_ADDITIONS.get(group, ()))))
        added += len(updated) - len(members)
        offsets.extend(struct.pack("<HH", len(card_ids), len(updated)))
        card_ids.extend(updated)
    if len(rows) > MAX_GROUPS or len(card_ids) > MAX_MEMBERSHIPS:
        raise ValueError("Patched group table exceeds the 80460 engine limits")
    data = struct.pack("<HH", len(rows), len(card_ids)) + offsets + struct.pack(f"<{len(card_ids)}H", *card_ids)
    return data, added


def install(project, backup_directory):
    engine = project / "Mods/Master Duel Engine"
    if sha256((engine / "duel.dll").read_bytes()).hexdigest() != ENGINE_HASH:
        raise ValueError("These card groups require the 80460 duel engine")
    table = engine / TABLE_NAME
    original = table.read_bytes()
    updated, added = apply_memberships(original)
    if updated == original:
        return {"added_memberships": 0}

    backup_directory.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(dir=table.parent, prefix=".card-groups-") as directory:
        staged = Path(directory) / TABLE_NAME
        staged.write_bytes(updated)
        with NamedTemporaryFile(dir=backup_directory, prefix="CARD_Named_80460.before-family-repair-",
                                suffix=".bin", delete=False) as backup:
            backup.write(original)
        if table.read_bytes() != original:
            raise RuntimeError("The installed card group table changed during the repair")
        os.replace(staged, table)
    return {"added_memberships": added, "backup": backup.name, "sha256": sha256(updated).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--backup-dir", type=Path,
                        default=Path(os.environ["LOCALAPPDATA"]) / "YGO-PC-Full/CardCatalog/pc-duel-backups")
    args = parser.parse_args()
    print(json.dumps(install(args.project, args.backup_dir)))


if __name__ == "__main__":
    main()
